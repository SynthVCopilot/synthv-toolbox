import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const read = (filename) => readFileSync(join(root, filename), "utf8").replace(/\r\n/g, "\n");
const workflow = read(".github/workflows/ffmpeg-verify.yml");
const prepare = read(".github/workflows/prepare-desktop.yml");
const release = read(".github/workflows/desktop.yml");
const ciConfig = read(".github/tauri-ci.conf.json");
const viteConfig = read("src/PiDesktop.Tauri/vite.config.ts");

assert.match(workflow, /^name: Toolbox Dev Build\n/);
assert.match(workflow, /^on:\n  pull_request:\n  push:\n    branches: \[main\]\n  workflow_dispatch:\n/m);
assert.match(workflow, /prepare:\n    uses: \.\/\.github\/workflows\/prepare-desktop\.yml\n    with:\n      release: false/);
assert.match(release, /prepare:\n    uses: \.\/\.github\/workflows\/prepare-desktop\.yml\n    with:\n      release: true/);
assert.match(prepare, /runs-on: ubuntu-latest/);
assert.match(prepare, /name: prepared-desktop/);
assert.match(prepare, /src\/PiDesktop\.Tauri\/dist/);
assert.match(prepare, /src\/PiDesktop\.Tauri\/src-tauri\/components\/synthv-agent-bridge\/dist/);
assert.match(prepare, /src\/PiDesktop\.Tauri\/src-tauri\/Cargo\.toml/);
assert.match(prepare, /npm run test:contracts/);
assert.match(prepare, /python -m py_compile/);
assert.match(prepare, /cargo fmt .* --check/);
assert.match(workflow, /name: prepared-desktop\n          path: src\/PiDesktop\.Tauri/);
assert.match(release, /name: prepared-desktop\n          path: src\/PiDesktop\.Tauri/);
assert.equal((workflow.match(/needs: prepare/g) ?? []).length, 2);
assert.equal((release.match(/needs: prepare/g) ?? []).length, 2);
assert.equal((workflow.match(/actions\/download-artifact@v5/g) ?? []).length, 2);
assert.equal((release.match(/actions\/download-artifact@v5/g) ?? []).length, 3);
assert.equal((workflow.match(/npm run build/g) ?? []).length, 0);
assert.equal((workflow.match(/npm run tauri build/g) ?? []).length, 1);
assert.doesNotMatch(workflow, /npm ci --omit=dev/);
assert.match(workflow, /--config \.\.\/\.\.\/\.github\/tauri-ci\.conf\.json/);
assert.match(ciConfig, /"beforeBuildCommand": ""/);
assert.match(viteConfig, /target: \["chrome111", "safari15"\]/);
assert.doesNotMatch(viteConfig, /TAURI_ENV_PLATFORM/);
assert.doesNotMatch(viteConfig, /chrome105|safari13/);
assert.match(workflow, /Download and smoke-test fixed BtbN LGPL FFmpeg/);
assert.match(workflow, /Smoke-test macOS system FFmpeg when available/);
assert.match(workflow, /Clear previous Windows bundle output/);
assert.match(workflow, /Clear previous macOS bundle output/);
assert.match(workflow, /dmg_count=.*test "\$dmg_count" -eq 1/s);
assert.match(workflow, /app_count=.*test "\$app_count" -eq 1/s);
assert.match(workflow, /rust_tests:/);
assert.match(workflow, /bundles: nsis/);
assert.match(workflow, /bundles: app,dmg/);
assert.match(workflow, /target: x86_64-pc-windows-msvc/);
assert.match(workflow, /target: universal-apple-darwin/);
assert.match(workflow, /actions\/cache@v5/);
assert.doesNotMatch(workflow, /actions\/cache@v4/);
assert.equal((workflow.match(/actions\/upload-artifact@v7/g) ?? []).length, 1);
assert.match(workflow, /artifact_suffix: -nsis\.exe/);
assert.match(workflow, /artifact_suffix: \.dmg/);
assert.match(workflow, /synthv-toolbox-\$\{\{ needs\.prepare\.outputs\.version \}\}-\$\{\{ matrix\.target \}\}\$\{\{ matrix\.artifact_suffix \}\}/);
assert.match(workflow, /synthv-toolbox-\$\{\{ needs\.prepare\.outputs\.version \}\}-\$\{\{ matrix\.target \}\}\.dmg/);
assert.match(workflow, /synthv-toolbox-\$\{\{ needs\.prepare\.outputs\.version \}\}-\$\{\{ matrix\.target \}\}-nsis\.exe/);
assert.match(workflow, /synthv-toolbox-artifacts\/\$\{\{ matrix\.target \}\}/);
assert.match(workflow, /archive: false/);
assert.doesNotMatch(workflow, /\.app\.zip/);
assert.equal((workflow.match(/if-no-files-found: error/g) ?? []).length, 1);
assert.equal((workflow.match(/retention-days: 14/g) ?? []).length, 1);
assert.match(workflow, /name: Upload development build artifact/);
assert.match(release, /needs: \[build, rust_tests\]/);
assert.match(release, /merge-multiple: true/);

console.log("Shared preparation workflow contracts passed.");
execFileSync(process.execPath, [join(root, "test", "dev-build-version.mjs")], { stdio: "inherit" });
